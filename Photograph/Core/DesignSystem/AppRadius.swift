import SwiftUI

/// AppRadius defines the standard corner radii according to the Design System
enum AppRadius {
    /// 8pt
    static let small: CGFloat = 8
    
    /// 12pt
    static let medium: CGFloat = 12
    
    /// 16pt
    static let large: CGFloat = 16
    
    /// 20pt (Often used as capsule radius)
    static let capsule: CGFloat = 20
    
    /// 62pt
    static let veryVeryLarge: CGFloat = 62
}
